import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'

async function logIn(page: Page) {
  await page.goto('/admin')
  const password = process.env.E2E_ADMIN_PASSWORD
  if (!password) throw new Error('Set E2E_ADMIN_PASSWORD for a disposable test application.')
  await page.getByLabel('Admin password').fill(password)
  await page.getByRole('button', { name: 'Open admin' }).click()
  await expect(page.getByRole('heading', { name: 'Surveys' })).toBeVisible()
}

test('build, preview, publish, collect, and export on a clean service', async ({ page, browser }) => {
  const title = 'Synthetic dust survey ' + Date.now()
  await logIn(page)
  await page.getByRole('link', { name: 'New survey' }).click()
  await page.getByLabel('Survey name').fill(title)
  await page.getByRole('button', { name: 'Create survey' }).click()
  await expect(page.getByRole('heading', { name: 'Survey builder' })).toBeVisible()
  const editor = new URL(page.url()).pathname
  const questionButtons = page.getByRole('region', { name: 'Survey questions' }).locator('.question-select')

  await page.getByRole('button', { name: 'Short text', exact: true }).dragTo(page.locator('.drop-zone'))
  await page.getByLabel('Question wording').fill('Sample code')
  await page.getByLabel('Required', { exact: true }).check()
  await page.getByRole('button', { name: 'Single choice', exact: true }).click()
  await page.getByLabel('Question wording').fill('Room')
  await page.getByLabel('Choice 1', { exact: true }).fill('Bedroom')
  await page.getByLabel('Choice 2', { exact: true }).fill('Kitchen')
  await page.getByLabel('Required', { exact: true }).check()
  await page.getByRole('button', { name: 'Move up: Room' }).click()
  await expect(questionButtons.first()).toContainText('Room')
  await page.locator('.question-card').first().locator('.drag-grip').dragTo(page.locator('.drop-zone'))
  await expect(questionButtons.first()).toContainText('Sample code')
  await page.getByRole('button', { name: 'Whole number', exact: true }).click()
  await page.getByLabel('Question wording').fill('Days since cleaning')
  await page.getByLabel('Unit').fill('days')
  await page.getByLabel('Minimum').fill('0')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Draft saved.')).toBeVisible()
  await page.reload()
  await expect(questionButtons).toHaveCount(3)
  await expect(questionButtons.first()).toContainText('Sample code')

  await page.getByRole('button', { name: 'Preview', exact: true }).click()
  const preview = page.getByRole('dialog')
  await preview.getByLabel('Sample code').fill('PREVIEW')
  await preview.getByRole('radio', { name: 'Bedroom' }).check()
  await preview.getByRole('button', { name: 'Test preview' }).click()
  await expect(preview.getByRole('heading', { name: 'Preview complete' })).toBeVisible()
  await preview.getByRole('button', { name: 'Close preview' }).click()

  await page.getByRole('link', { name: 'Responses' }).click()
  await expect(page.getByText('No published versions')).toBeVisible()
  await page.goto(editor)
  await page.getByRole('button', { name: 'Publish', exact: true }).click()
  await expect(page.getByText('Survey published. You can now copy the participant link.')).toBeVisible()
  const origin = new URL(page.url()).origin
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.getByRole('button', { name: 'Copy link' }).click()
  const participantUrl = await page.evaluate(() => navigator.clipboard.readText())
  expect(participantUrl).toContain(origin + '/s/')

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 })
  const respondent = await mobile.newPage()
  await respondent.goto(participantUrl)
  await expect(respondent.getByRole('heading', { name: title })).toBeVisible()
  await expect(respondent.getByRole('link', { name: 'Dust Survey' })).toHaveCount(0)
  await expect(respondent.locator('body')).toHaveJSProperty('scrollWidth', 390)
  await respondent.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(respondent.getByText('Check the highlighted answers.')).toBeVisible()
  await respondent.getByLabel('Sample code').fill('DEMO-001')
  await respondent.getByRole('radio', { name: 'Kitchen' }).check()
  await respondent.getByLabel('Days since cleaning').fill('-1')
  await respondent.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(respondent.getByText('Enter a value of 0 or more.')).toBeVisible()
  await respondent.reload()
  await expect(respondent.getByLabel('Sample code')).toHaveValue('DEMO-001')
  await respondent.getByLabel('Days since cleaning').fill('0')
  await respondent.route('**/api/public/surveys/*/responses', route => route.abort(), { times: 1 })
  await respondent.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(respondent.getByRole('alert')).toContainText('Could not reach')
  await expect(respondent.getByLabel('Sample code')).toHaveValue('DEMO-001')
  await respondent.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(respondent.getByRole('heading', { name: 'Your response has been saved' })).toBeVisible()
  await mobile.close()

  const desktop = await browser.newContext({ viewport: { width: 1280, height: 800 } })
  const second = await desktop.newPage()
  await second.goto(participantUrl)
  await second.getByLabel('Sample code').fill('DEMO-002')
  await second.getByRole('radio', { name: 'Bedroom' }).check()
  await second.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(second.getByRole('heading', { name: 'Your response has been saved' })).toBeVisible()
  await desktop.close()

  await page.getByRole('link', { name: 'Responses' }).click()
  await expect(page.getByRole('heading', { name: 'Version 1 responses' })).toBeVisible()
  await expect(page.getByText('2 saved', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Open response' })).toHaveCount(2)
  await page.getByRole('button', { name: 'Open response' }).last().click()
  await expect(page.getByText('DEMO-001')).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('link', { name: 'Download CSV' }).click()
  expect((await download).suggestedFilename()).toMatch(/v1-responses\.csv$/)
  await page.getByRole('button', { name: 'Lock admin' }).click()
  await expect(page.getByLabel('Admin password')).toBeVisible()
  await expect((await page.request.get(editor.replace('/edit', '/results').replace('/admin', '/api/admin'))).status()).toBe(401)
})
